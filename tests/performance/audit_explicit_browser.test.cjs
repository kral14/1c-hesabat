const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
(async()=>{
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const page = await browser.newPage({viewport:{width:1600,height:950}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const css=['1c_base','1c_toolbar','1c_mdi','list_appearance'].map(n=>fs.readFileSync(`static/css/${n}.css`,'utf8')).join('\n');
  const html=['audit_journal_window','universal_journal_filter_window'].map(n=>fs.readFileSync(`templates/components/${n}.html`,'utf8')).join('\n');
  await page.setContent(`<style>${css} body{margin:0;background:#ece9d8;} #auditJournalWindow{inset:0;width:100%;height:100%;}</style>${html}`);
  await page.evaluate(()=>{
    const storage=new Map();Object.defineProperty(window,'localStorage',{value:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)}});
    window.SessionManager={getCredentials:()=>({server:'Test1C',ref:'Aztrade_test3'})};
    window.requests=[];window.alerts=[];window.alert=m=>alerts.push(m);
    window.fetch=async(url,opts)=>{requests.push({url,payload:JSON.parse(opts.body)});return {json:async()=>({success:true,items:[]})};};
  });
  for(const file of ['form_action','mdi_manager','c1_filter_component','list_appearance','universal_journal','audit_journal'])await page.addScriptTag({content:fs.readFileSync(`static/js/${file}.js`,'utf8')});
  await page.evaluate(()=>{MdiManager.init();AuditJournal.init();AuditJournal.open();});
  assert.equal(await page.evaluate(()=>requests.length),0);
  await page.locator('#ajDocTypeSelect').selectOption('ВозвратТоваровОтПокупателя');
  await page.locator('#ajPeriodField').selectOption('date');
  await page.getByRole('button',{name:'Фильтр',exact:true}).click();
  await page.evaluate(()=>{C1FilterComponent.addFilterCriterion('number');const i=C1FilterComponent.tempFilterCriteria.length-1;C1FilterComponent.tempFilterCriteria[i].value='TEST-NUMBER';C1FilterComponent.tempFilterCriteria[i].enabled=true;C1FilterComponent.renderFilterCriteriaRows();});
  await page.screenshot({path:'tests/artifacts/audit_explicit_filter.png'});
  await page.locator('#ujFilterWindow .mdi-win-btn-close').click();
  assert.equal(await page.evaluate(()=>requests.length),0);
  await page.getByRole('button',{name:'Фильтр',exact:true}).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>requests.length),0);
  await page.getByRole('button',{name:'Фильтр',exact:true}).click();
  await page.evaluate(()=>{C1FilterComponent.addFilterCriterion('number');const i=C1FilterComponent.tempFilterCriteria.length-1;C1FilterComponent.tempFilterCriteria[i].value='TEST-NUMBER';C1FilterComponent.tempFilterCriteria[i].enabled=true;C1FilterComponent.renderFilterCriteriaRows();});
  await page.locator('#ujFilterConfirmButton').focus();
  await page.keyboard.press('Control+Enter');
  assert.equal(await page.evaluate(()=>requests.length),1);
  assert.equal(await page.locator('#ujFilterWindow').isVisible(),false);
  assert.equal(await page.locator('#auditJournalWindow').isVisible(),true);
  const payload=await page.evaluate(()=>requests[0].payload);
  assert.equal(payload.filters.find(f=>f.fieldKey==='number').value,'TEST-NUMBER');
  assert.equal(payload.period_field,'date');
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: open, type/date changes, X, Escape, Ctrl+Enter, filter payload and result window.');
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});

const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const messages=[];
const ctx=vm.createContext({console,window:{},document:{getElementById:()=>null},alert:m=>messages.push(m)});
ctx.window=ctx;ctx.addEventListener=()=>{};
vm.runInContext(fs.readFileSync('static/js/c1_dates.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('static/js/c1_filter_component.js','utf8')+';globalThis.f=C1FilterComponent;',ctx);
const f=ctx.f;
f.availableFields=[{key:'number',type:'text'},{key:'amount',type:'number'},{key:'date',type:'date'},{key:'warehouse',type:'text'}];
f.isFieldInCurrentDoc=()=>true;
const rule=(fieldKey,value,operator='Равно',extra={})=>({fieldKey,value,operator,...extra});
assert.equal(f.validateCriteria([rule('number','14')]),false);
assert.equal(f.validateCriteria([rule('number','C0000476122')]),true);
for(const op of ['Содержит','Не содержит','Начинается с','Заполнено','Не заполнено']) {
  assert.equal(f.validateCriteria([rule('number','14',op)]),true);
  assert.ok(f.getOperatorsForField({key:'number'}).includes(op));
}
for(const op of ['Равно','Не равно','В списке','Не в списке','В группе из списка']) assert.equal(f.validateCriteria([rule('number','14',op)]),false);
for(const op of ['В списке','Не в списке','В группе из списка']) {
  assert.equal(f.validateCriteria([rule('number','C0000476122; C0000476123',op)]),true);
  assert.equal(f.validateCriteria([rule('number','C0000476122; 14',op)]),false);
}
for(const op of ['Заполнено','Не заполнено']) assert.equal(f.validateCriteria([rule('number','',op)]),true);
assert.equal(f.validateCriteria([rule('number','C0000476122','В группе из списка',{structuredFilter:{items:[{comp:'contains',value:'14'}]}})]),false);
assert.equal(f.matchesCondition({number:'C0000476122'},rule('number','C0000476122; C0000476123','В списке')),true);
assert.equal(f.matchesCondition({number:'XC0000476122'},rule('number','C0000476122; C0000476123','В списке')),false);
assert.equal(f.validateCriteria([rule('warehouse','WH','Содержит')]),false);
assert.equal(f.validateCriteria([rule('date','31.02.2026')]),false);
assert.equal(f.validateCriteria([rule('amount','NaN')]),false);
assert.equal(f.validateCriteria([rule('amount','','Интервал (>=, <=)',{valueFrom:'20',valueTo:'10'})]),false);
assert.equal(f.validateCriteria([rule('number','14','Равно',{enabled:false})]),true);
console.log('Common filter policy checks passed');

let saves=0;
f.syncTempFiltersToStorage=()=>saves++;
f.updateHeaderCheckAllState=()=>{};
const checkbox={checked:true};
ctx.document.getElementById=id=>id==='ujCritEnabled_0'?checkbox:null;
f.showFilterAutocomplete=()=>{};
const input={value:'14',style:{},dataset:{},classList:{contains:()=>false},setCustomValidity(v){this.validityMessage=v;},setAttribute(){}};
f.tempFilterCriteria=[rule('number','', 'Равно')];
const before=messages.length;
f.onFilterValueInput(0,input,{});
assert.ok(input.validityMessage.includes('Tam sənəd'));
assert.equal(messages.length,before);
assert.equal(saves,0);
assert.equal(checkbox.checked,false,'partial input must not enable criterion');
assert.equal(f.tempFilterCriteria[0].enabled,false);
f.onFilterSingleBlur(0,input);
assert.equal(messages.length,before+1);
assert.equal(input.value,'','invalid value is removed from input');
assert.equal(f.tempFilterCriteria[0].value,'','invalid value is removed from criterion');
assert.equal(f.tempFilterCriteria[0].enabled,false);
assert.equal(checkbox.checked,false);
f.onFilterSingleBlur(0,input);
assert.equal(messages.length,before+1,'empty field does not repeat warning');
input.value='14';
let prevented=false,stopped=false;
f.onFilterInputKeydown(0,input,{key:'Enter',preventDefault(){prevented=true;},stopPropagation(){stopped=true;}});
assert.ok(prevented && stopped);
assert.equal(input.value,'');assert.equal(checkbox.checked,false);
input.value='C0000476122';f.onFilterValueInput(0,input,{});
assert.equal(input.validityMessage,'');assert.equal(checkbox.checked,true);
f.tempFilterCriteria[0].operator='Содержит';input.value='14';f.onFilterSingleBlur(0,input);
assert.equal(input.validityMessage,'');assert.equal(input.value,'14');assert.equal(checkbox.checked,true);
console.log('Rejected number is cleared and unchecked; valid and contains values remain accepted');

f.tempFilterCriteria[0].operator='Начинается с';input.value='14';
const hintBefore=messages.length;
f.onFilterSingleBlur(0,input);
assert.equal(messages.length,hintBefore+1);
assert.ok(messages.at(-1).includes('C000'));
assert.ok(messages.at(-1).includes('Содержит'));
assert.equal(input.value,'','ambiguous prefix is cleared on commit');assert.equal(checkbox.checked,false);
f.onFilterSingleBlur(0,input);assert.equal(messages.length,hintBefore+1);
input.value='C000';f.onFilterSingleBlur(0,input);assert.equal(input.title,'');
console.log('Starts-with guidance checks passed');


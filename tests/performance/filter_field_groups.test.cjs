const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const list = {innerHTML:''};
const context = vm.createContext({window:{},console,document:{getElementById:()=>list}});
vm.runInContext(fs.readFileSync('static/js/c1_filter_component.js','utf8'),context);
const filter = context.window.C1FilterComponent;
filter.availableFields = ['date','kontragent','golovnoy_kontragent','kontragent_code','contract','portfolio','pogruzka_marshrut','pogruzka_duplicate'].map(key=>({key,label:key}));
const tree = filter.getAvailableFieldTree();
assert.equal(tree.find(n=>n.id==='kontragent').children.length,2);
assert.equal(tree.find(n=>n.id==='pogruzka').children.length,2);
const keys = tree.flatMap(n=>[...(n.field?[n.field.key]:[]),...(n.children||[]).map(f=>f.key)]);
assert.equal(keys.length, filter.availableFields.length);
assert.equal(new Set(keys).size,keys.length);
filter.renderFilterAvailableFields();
assert.ok(!list.innerHTML.includes('id="ujAvailField_golovnoy_kontragent"'));
filter.toggleFieldGroup('kontragent');
assert.ok(list.innerHTML.includes('id="ujAvailField_golovnoy_kontragent"'));
assert.ok(list.innerHTML.includes('aria-expanded="true"'));
filter.toggleFieldGroup('kontragent');
assert.ok(!list.innerHTML.includes('id="ujAvailField_golovnoy_kontragent"'));
console.log('Grouped field tree checks passed; all fields preserved and groups collapse/expand.');
